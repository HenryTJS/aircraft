# -*- coding: utf-8 -*-
"""Tests for the claim–evidence contract.

The valid graph is generated by tools/build_claim_graph.py from raw L1-06;
validator re-executes the metric, so these tests need E:/l1 mounted.
"""
import copy
import json
import os
import unittest

from validate import validate_graph

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SCHEMA = os.path.join(ROOT, "schema", "claim_evidence.schema.json")
EXAMPLE = os.path.join(ROOT, "examples", "L1-06_t85.json")
EXAMPLE_T062 = os.path.join(ROOT, "examples", "L1-06_t85_at062.json")
L1_DATA = "E:/l1"


def load(path=EXAMPLE):
    with open(SCHEMA, encoding="utf-8") as fh:
        schema = json.load(fh)
    with open(path, encoding="utf-8") as fh:
        graph = json.load(fh)
    return schema, graph


@unittest.skipUnless(os.path.isdir(L1_DATA), "E:/l1 not mounted")
class TestClaimEvidence(unittest.TestCase):
    def test_valid_example_passes(self):
        schema, graph = load()
        rep = validate_graph(graph, schema)
        self.assertEqual(rep.failed, [], rep.failed)

    def test_temporal_example_fails(self):
        schema, graph = load(EXAMPLE_T062)
        rep = validate_graph(graph, schema)
        self.assertTrue(any(c["name"] == "temporal_leakage" for c in rep.failed),
                        rep.failed)

    def test_missing_evidence_fails(self):
        schema, graph = load()
        g = copy.deepcopy(graph)
        g["claims"][0]["evidence_ids"] = []
        g["edges"] = [e for e in g["edges"] if e["claim_id"] != "C001"]
        rep = validate_graph(g, schema)
        self.assertTrue(rep.failed)
        self.assertTrue(any(c["name"] == "claim_evidence" for c in rep.failed))

    def test_numeric_mismatch_fails(self):
        schema, graph = load()
        g = copy.deepcopy(graph)
        g["claims"][0]["value"] = 90.0
        rep = validate_graph(g, schema)
        self.assertTrue(any(c["name"] == "numeric_value" for c in rep.failed))

    def test_missing_tool_call_id_fails(self):
        schema, graph = load()
        g = copy.deepcopy(graph)
        g["evidence"][0]["tool_call_id"] = None
        rep = validate_graph(g, schema)
        self.assertTrue(any(c["name"] == "tool_call_binding" for c in rep.failed))

    def test_missing_coverage_fails(self):
        schema, graph = load()
        g = copy.deepcopy(graph)
        g["evidence"][0]["coverage"] = None
        rep = validate_graph(g, schema)
        self.assertTrue(any(c["name"] == "coverage" for c in rep.failed))

    def test_unknown_tool_fails(self):
        schema, graph = load()
        g = copy.deepcopy(graph)
        g["tool_calls"][0]["tool_name"] = "metric.does_not_exist"
        rep = validate_graph(g, schema)
        self.assertTrue(any(c["name"] == "tool_reexecution" for c in rep.failed))

    def test_reexecution_catches_consistent_tamper(self):
        schema, graph = load()
        g = copy.deepcopy(graph)
        # Make claim, evidence and tool_call agree on a wrong value: only
        # re-execution can catch this.
        g["claims"][0]["value"] = 90.0
        g["evidence"][0]["content"]["value"] = 90.0
        g["tool_calls"][0]["result"]["t85_pct"] = 90.0
        rep = validate_graph(g, schema)
        self.assertTrue(any(c["name"] == "tool_reexecution" for c in rep.failed),
                        rep.failed)

    def test_temporal_leakage_fails(self):
        schema, graph = load()
        g = copy.deepcopy(graph)
        g["claims"][0]["allowed_lifetime_max"] = 0.5
        rep = validate_graph(g, schema)
        self.assertTrue(any(c["name"] == "temporal_leakage" for c in rep.failed))


class TestCheckedInInvalidExamples(unittest.TestCase):
    def test_checked_in_invalid_examples_fail(self):
        schema, _ = load()
        for name in ("invalid_missing_evidence.json", "invalid_temporal_leakage.json"):
            with open(os.path.join(ROOT, "examples", name), encoding="utf-8") as fh:
                g = json.load(fh)
            rep = validate_graph(g, schema)
            self.assertTrue(rep.failed, name)


if __name__ == "__main__":
    unittest.main()
